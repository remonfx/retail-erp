#!/usr/bin/env python3
"""Regenerate the endpoint table at the end of docs/API_DOCUMENTATION.md from route() calls in apps/api/src."""
import glob, re, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for f in sorted(glob.glob(f'{ROOT}/apps/api/src/modules/**/*.ts', recursive=True)):
    src = open(f, encoding='utf-8').read()
    mod = os.path.relpath(f, f'{ROOT}/apps/api/src/modules').replace('/routes.ts', '').replace('.ts', '')
    for m in re.finditer(r"route\(app, '(GET|POST|PATCH|PUT|DELETE)', '([^']+)', \{", src):
        opts = src[m.end():src.find('}, async', m.end())]
        auth = re.search(r"auth: '([a-z_]+)'", opts)
        perm = re.search(r"perm: '([a-z_.]+)'", opts)
        rows.append(f"| {m.group(1)} | `{m.group(2)}` | {auth.group(1) if auth else 'user'} | {perm.group(1) if perm else 'checked in handler (scope-aware)'} | {mod} |")

doc = f'{ROOT}/docs/API_DOCUMENTATION.md'
text = open(doc, encoding='utf-8').read()
marker = '## 10. Endpoint reference'
text = text[:text.index(marker)] if marker in text else text + '\n'
text += (f"{marker} ({len(rows)} endpoints, generated by tools/gen-api-docs.py)\n\n"
         "Every non-GET user request requires `Idempotency-Key`. Permission column shows the route-level guard; "
         "branch/warehouse scope is verified inside handlers against the resolved document.\n\n"
         "| Method | Path | Auth | Permission | Module |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
open(doc, 'w', encoding='utf-8').write(text)
print(len(rows), 'endpoints')
